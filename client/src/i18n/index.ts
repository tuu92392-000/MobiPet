export const DICTS: Record<Lang, Record<MsgKey, string>> = { en, es };

export type Translate = (key: MsgKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): Translate {
  return (key, vars) => {
    const template = DICTS[lang][key] ?? en[key];
    return vars ? template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : template;
  };
}
